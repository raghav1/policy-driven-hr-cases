#!/usr/bin/env python3
"""Writes servicenow-app/scripts/seed-hr-data.js: a one-time seed for HR policies and routing rules.

Policies and routing rules are owned by HR in the ServiceNow UI, so they are not part of the app
package (a redeploy would overwrite UI edits). This script creates whatever is missing and never
changes records that already exist.

Usage: python3 scripts/build_seed_script.py
Then:  cd servicenow-app && npx now-sdk exec --auth pdi -f scripts/seed-hr-data.js \
           --scope 77e3b6970d2d4d759440ba33ca5637df --reason "Seed HR policies and routing rules"
"""

