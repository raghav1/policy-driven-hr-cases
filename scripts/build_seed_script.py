LOGIC = r"""
function ensureKb() {
    var kb = new GlideRecord('kb_knowledge_base');
    if (kb.get(KB.sys_id)) return 'kept';
    kb.initialize();
    kb.setNewGuidValue(KB.sys_id);
    kb.setValue('title', KB.title);
    kb.setValue('description', KB.description);
    kb.setValue('owner', KB.owner);
    kb.setValue('kb_version', '3');
    kb.setValue('active', true);
    kb.insert();
    return 'created';
}

function idOf(table, field, value) {
    var gr = new GlideRecord(table);
    return value && gr.get(field, value) ? gr.getUniqueValue() : '';
}

var summary = {
    kb: ensureKb(), articlesCreated: 0, articlesKept: 0, rulesCreated: 0, rulesKept: 0,
};

for (var i = 0; i < ARTICLES.length; i++) {
    var a = ARTICLES[i];
    var art = new GlideRecord('kb_knowledge');
    if (art.get('number', a.number)) {
        summary.articlesKept++;
        continue;
    }
    art.initialize();
    art.setValue('number', a.number);
    art.setValue('kb_knowledge_base', KB.sys_id);
    art.setValue('short_description', a.title);
    art.setValue('text', a.html);
    art.setValue('meta', a.meta);
    art.setValue('workflow_state', 'published');
    art.setValue('article_type', 'text');
    art.setValue('valid_to', '2100-12-31');
    art.setValue('active', true);
    art.insert();
    summary.articlesCreated++;
}

for (var j = 0; j < RULES.length; j++) {
    var r = RULES[j];
    var rule = new GlideRecord('x_2312287_hrorch_routing_rule');
    if (rule.get('name', r.name)) {
        summary.rulesKept++;
        continue;
    }
    rule.initialize();
    rule.setValue('name', r.name);
    rule.setValue('order', r.order);
    rule.setValue('active', true);
    rule.setValue('category', r.category);
    rule.setValue('severity', r.severity);
    rule.setValue('assignment_group', idOf('sys_user_group', 'name', r.group));
    rule.setValue('assigned_to', idOf('sys_user', 'user_name', r.user));
    rule.setValue('description', r.description || '');
    rule.insert();
    summary.rulesCreated++;
}

gs.info('seed summary: ' + JSON.stringify(summary));
"""


def main() -> None:
    articles = []
    for path in sorted((ROOT / "corpus").glob("*.json")):
        a = json.loads(path.read_text())
        articles.append(
            {"number": a["number"], "title": a["title"], "meta": a["meta"], "html": a["html"]}
        )
    header = (
        "// Generated by scripts/build_seed_script.py from corpus/. Do not edit by hand.\n"
        "// Creates the HR Policies knowledge base, policy articles and routing rules when "
        "missing.\n"
        "// Never changes existing records, so edits made in the ServiceNow UI are kept.\n"
    )
    body = (
        f"var KB = {json.dumps(KB)};\n"
        f"var RULES = {json.dumps(RULES, indent=1)};\n"
        f"var ARTICLES = {json.dumps(articles)};\n"
    )
    OUT.write_text(header + body + LOGIC)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(articles)} articles, {len(RULES)} rules)")


if __name__ == "__main__":
    main()
